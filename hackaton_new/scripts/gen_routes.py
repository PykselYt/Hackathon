"""Generates sumo/routes.rou.xml: cars, buses and pedestrians, normal / peak / normal (PLAN.md §6 step 4).

    python scripts/gen_routes.py                 # default demand below
    python scripts/gen_routes.py --scale 1.2     # all vehicle rates x1.2

Arrivals are Poisson (period="exp(rate)"), so each SUMO seed gives different traffic.
vision/demand_from_video.py later overrides the rates measured from the camera.
"""
import argparse
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PERIODS = [(0, 1200), (1200, 2400), (2400, 3600)]

ROUTES = {
    # Ids used by config.yaml (rush_hour.routes) and the vision module (spawn approaches): partial routes at A
    "blv_dir1": "blv_w_in cuza_ab cuza_e_out",          # away from the camera (visible queue)
    "blv_dir2": "cuza_e_in cuza_ba blv_w_out",          # towards the camera
    "lat_in": "scm_in blv_w_out",                       # side street, right of the frame
    # Through traffic between the boundaries
    "garii_cuza": "garii_s_in blv_w_in cuza_ab cuza_e_out",
    "sarcu_cuza": "sarcu_in blv_w_in cuza_ab cuza_e_out",
    "cuza_garii": "cuza_e_in cuza_ba blv_w_out garii_s_out",
    "cuza_sarcu": "cuza_e_in cuza_ba blv_w_out sarcu_out",
    "garii_ns": "garii_n_in garii_s_out",
    "garii_sn": "garii_s_in garii_n_out",
    "indep_we": "indep_w_in indep_e_out",
    "indep_ew": "indep_e_in indep_w_out",
    "indep_unirii": "indep_e_in brat_n_in cuza_ba blv_w_out garii_s_out",
    "unirii_indep": "sarcu_in blv_w_in cuza_ab brat_n_out indep_w_out",
    "scm_loop_out": "sarcu_in blv_w_in scm_out brat_s_in brat_n_out indep_e_out",
    "scm_loop_in": "indep_w_in brat_n_in brat_s_out scm_in blv_w_out garii_n_out",
    "cuza_scm": "cuza_e_in brat_s_out scm_in blv_w_out sarcu_out",
}

# veh/h for (0-1200 s, 1200-2400 s, 2400-3600 s). Left turns across a heavy opposing flow are avoided:
# they are permissive in the network and block the inner lane.
CARS = {
    "sarcu_cuza": (450, 800, 450),       # main corridor: Șos. Arcu - Arcu - Cuza Vodă, straight through E and A
    "garii_cuza": (150, 250, 150),
    "cuza_sarcu": (400, 700, 400),
    "cuza_garii": (50, 80, 50),           # left turn at E
    "garii_ns": (100, 150, 100),
    "garii_sn": (100, 150, 100),
    "indep_we": (600, 1000, 600),
    "indep_ew": (600, 1000, 600),
    "indep_unirii": (100, 180, 100),
    "unirii_indep": (80, 140, 80),
    "scm_loop_out": (100, 180, 100),
    "scm_loop_in": (120, 200, 120),
    "cuza_scm": (80, 140, 80),
}
# buses: (route, period in s)
BUSES = {
    "garii_cuza": 360,
    "cuza_garii": 360,
    "scm_loop_in": 600,
    "indep_we": 480,
    "indep_ew": 480,
}
# pedestrians: (from edge, to edge, persons/h); they walk on sidewalks and use the signalised crossings
PEDESTRIANS = [
    ("blv_w_in", "cuza_ab", 160),       # across Piața Unirii
    ("cuza_ba", "scm_out", 140),
    ("scm_in", "blv_w_out", 140),
    ("scm_out", "brat_s_in", 180),      # Ștefan cel Mare towards Palatul Culturii, crossing at C
    ("brat_s_out", "scm_in", 160),
    ("cuza_ab", "brat_n_out", 90),
    ("brat_n_in", "cuza_e_out", 90),
    ("indep_w_in", "brat_n_in", 120),
    ("indep_e_in", "indep_w_out", 100),
    ("garii_s_in", "garii_n_out", 110),
    ("sarcu_in", "blv_w_in", 90),
]


# training only: Rush Hour-like bursts (start s, vehicles per route over BURST_S), so the policy has seen them
TRAIN_BURSTS = [(700, 100), (1650, 100), (2700, 100)]
BURST_S = 60
BURST_ROUTES = ["blv_dir1", "blv_dir2"]


def build(scale: float = 1.0, bursts: bool = False) -> str:
    out = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!-- Generated by scripts/gen_routes.py, do not edit by hand. -->",
        "<routes>",
        '    <vType id="car" accel="2.6" decel="4.5" length="4.5" minGap="2.5" maxSpeed="13.9" sigma="0.5"/>',
        '    <vType id="bus" vClass="bus" accel="1.2" decel="4.0" length="12" minGap="3" maxSpeed="13.9" sigma="0.3"/>',
        '    <vType id="ped" vClass="pedestrian" speed="1.3"/>',
    ]
    out += [f'    <route id="{rid}" edges="{edges}"/>' for rid, edges in ROUTES.items()]
    end = PERIODS[-1][1]
    for rid, period in BUSES.items():
        out.append(f'    <flow id="bus_{rid}" route="{rid}" type="bus" begin="0" end="{end}" period="{period}" '
                   f'departLane="best" departSpeed="max"/>')
    for k, (fr, to, pph) in enumerate(PEDESTRIANS):
        out.append(f'    <personFlow id="ped_{k}" type="ped" begin="0" end="{end}" period="exp({pph / 3600:.5f})">'
                   f'<walk from="{fr}" to="{to}"/></personFlow>')
    for k, (begin, stop) in enumerate(PERIODS):
        out.append(f"    <!-- cars {begin}-{stop} s -->")
        for rid, rates in CARS.items():
            vph = rates[k] * scale
            if vph > 0:
                out.append(f'    <flow id="f_{rid}_{k + 1}" route="{rid}" type="car" begin="{begin}" end="{stop}" '
                           f'period="exp({vph / 3600:.5f})" departLane="best" departSpeed="max"/>')
    if bursts:
        out.append("    <!-- training bursts (Rush Hour) -->")
        for k, (begin, n) in enumerate(TRAIN_BURSTS):
            for rid in BURST_ROUTES:
                out.append(f'    <flow id="burst_{rid}_{k}" route="{rid}" type="car" begin="{begin}" end="{begin + BURST_S}" '
                           f'period="exp({n / BURST_S:.5f})" departLane="best" departSpeed="max"/>')
    out.append("</routes>")
    return "\n".join(out) + "\n"


def check(net_path: Path) -> None:
    """Fail early if a route uses two edges that are not connected."""
    if "SUMO_HOME" not in os.environ:
        import sumo
        os.environ["SUMO_HOME"] = sumo.SUMO_HOME
    import sumolib
    net = sumolib.net.readNet(str(net_path))
    for rid, edges in ROUTES.items():
        es = edges.split()
        for a, b in zip(es, es[1:]):
            if net.getEdge(b) not in net.getEdge(a).getOutgoing():
                raise SystemExit(f"route {rid}: {a} -> {b} is not connected")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--scale", type=float, default=1.0)
    p.add_argument("--out", default=str(ROOT / "sumo/routes.rou.xml"))
    p.add_argument("--train-bursts", action="store_true", help="add Rush Hour-like bursts (training routes)")
    a = p.parse_args()
    check(ROOT / "sumo/net.net.xml")
    Path(a.out).write_text(build(a.scale, a.train_bursts), encoding="utf-8")
    print(f"OK: {a.out}")


if __name__ == "__main__":
    main()
